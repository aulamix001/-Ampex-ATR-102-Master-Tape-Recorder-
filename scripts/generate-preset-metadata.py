#!/usr/bin/env python3
"""Generate the native UTF-8 preset metadata from the supplied JSON."""
import json
from pathlib import Path
root = Path(__file__).resolve().parent.parent
source = (root / 'presets/presets.json').read_text(encoding='utf-8')
data = json.loads(source)['presets']
assert len(data) == 8 and len({p['name'] for p in data}) == 8
assert all(p['name'] and p['description'] for p in data)
header = ('// Generated by scripts/generate-preset-metadata.py; edit presets/presets.json.\n'
          '#pragma once\n'
          'static constexpr const char* presetMetadataJson = u8R"PRESETS(' + source + ')PRESETS";\n')
(root / 'Source/PresetMetadata.h').write_text(header, encoding='utf-8')
